/// نمط التحقق من البريد الإلكتروني — نسخة مبسّطة من RFC 5322.
///
/// ملاحظات:
/// - `^` و `$` إلزاميان: بلاهما يُقبل "user@example.com أي نفايات".
/// - لا يتكرر شريط الحروف (كان `[a-zA-Z0-9.a-zA-Z0-9.!#...]` بالنسخة القديمة).
/// - يترفض: `a@b` (بدون نقطة)، `.@.`, `@.com`, النصوص بعد النطاق.
const String emailPattern =
    r"^[a-zA-Z0-9.!#$%&'*+/=?^_`{|}~-]+@[a-zA-Z0-9](?:[a-zA-Z0-9-]*[a-zA-Z0-9])?(?:\.[a-zA-Z0-9](?:[a-zA-Z0-9-]*[a-zA-Z0-9])?)*\.[a-zA-Z]{2,}$";
